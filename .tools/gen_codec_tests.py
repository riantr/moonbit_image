def literal(data: bytes) -> str:
    """Byte-exact MoonBit byte-string literal.

    Every byte is escaped as \\xNN so the literal is pure ASCII and can
    never be re-interpreted as UTF-8 multi-byte sequences.
    """
    return 'b"' + "".join("\\x%02x" % b for b in data) + '"'


