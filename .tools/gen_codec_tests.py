"""Generate the codec decode tests + inline byte fixtures for
riantr/moonbit_image.

Reads the real samples from testdata/ and emits
`lib_test_codecs.mbt` containing:
  * one `fixture_<name>()` fn per sample, returning the byte-for-byte file
  * decode tests for JPEG / PNG / GIF / TGA

The generated file is a normal test file (no `import` statements, per the
current MoonBit package system) and lives next to lib_test.mbt.

Usage (from the module root):

    python .tools/gen_codec_tests.py

The script runs `moon fmt` afterwards so the generated file matches the
formatter's canonical form — otherwise `moon fmt --check` (a release
gate) would fail on the freshly generated output.

Re-run it whenever a sample in testdata/ changes; the fixtures are the
real files, byte for byte.
"""
