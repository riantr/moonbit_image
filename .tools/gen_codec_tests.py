def main():
    out = [HEADER]
    for fn_suffix, rel, label in SAMPLES:
        path = os.path.join(TD, rel)
        with open(path, "rb") as fh:
            data = fh.read()
        out.append("")
        out.append("///|")
        out.append("/// %s (testdata/%s, %d bytes)" % (label, rel.replace("\\", "/"), len(data)))
        out.append("fn fixture_%s() -> Bytes {" % fn_suffix)
        out.append("  " + literal(data))
        out.append("}")
    out.append(TESTS)
    out.append(GOLDEN_TESTS)

    target = os.path.join(ROOT, "lib_test_codecs.mbt")
    with open(target, "w", encoding="utf-8", newline="\n") as fh:
        fh.write("\n".join(out))
    print("wrote", target, os.path.getsize(target), "bytes")

    # Format the generated file so it matches `moon fmt --check`, which is
    # a release gate. Failure here is not fatal: the file is still valid
    # MoonBit, it just needs a manual `moon fmt`.
    moon = "moon.exe" if sys.platform == "win32" else "moon"
    try:
        subprocess.run([moon, "fmt"], cwd=ROOT, check=True,
                       stdout=subprocess.PIPE, stderr=subprocess.STDOUT)
        print("moon fmt: ok")
    except FileNotFoundError:
        print("moon fmt: skipped (moon not on PATH)")
    except subprocess.CalledProcessError as exc:
        out = (exc.output or b"").decode("utf-8", "replace")
        print("moon fmt: FAILED\n" + out[-2000:])
        print("run `moon fmt` manually in the module root")


if __name__ == "__main__":
    main()
